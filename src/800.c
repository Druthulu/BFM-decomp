        goto state2;
    case 3:
        CdControl(0x15, (u8 *)cdReq_cdlFile, &cdReq_cdResult);    /* CdlSeekL */
        if ((cdReq_cdResult & 0x10) == 0) {
            cdReq_timeout = 0;
            cdReq_posInt = CdPosToInt((CdlLOC *)cdReq_cdlFile);
            cdReq_state++;
            goto state4;
        }
        break;
    case 4:
    state4:
        D_800AE6E8 = CdSync(1, &cdReq_cdResult);
        if (D_800AE6E8 == 5) {
            cdReq_retry++;
        flushRetry:
            CdFlush();
            cdReq_state = 3;
            cdReq_result = 0;
            return;
        }
