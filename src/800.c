        if (D_800AE6E8 == 2) {
            cdReq_sink = (s32)start;
            cdReq_state = 0;
            D_800AE6F8 = 0;
            D_800AE6FC = 0;
            D_800AE700 = 0;
            cdReq_curSector = 0;
            D_800AE70C = 0;
            cdReq_wordsRemaining = 1;
            cdReq_drainPhase = 0;
            D_800AE798 = 0;
            D_800AE799 = 0;
            cdReq_result = 1;
            return;
        }
        if (D_800AE6E8 != 5) { cdReq_result = 0; return; }
        CdFlush();
        CdControl(0x09, (u8 *)0, &cdReq_cdResult);                /* CdlPause */
