#!/usr/bin/env python3
"""delever_search.py — rung G of the lever ladder: the GUIDED search for a lever-free body (Phase 36, S101).

    tools/delever_search.py --plan [--limit N] [--only X ...] [--score]      # the residue's exemplars; --score = their starting distance
    tools/delever_search.py --run [--limit K] [--only X ...] [-j W] [--beam B] [--depth D] [--cap C] [--budget M] [--label gN]
    tools/delever_search.py --positive-control TU FN [--moves 1|2]           # perturb a MATCHING body, require the search to return to 0
    tools/delever_search.py --try TU FN FILE [--body]                       # score a candidate WITHOUT writing the tree (an agent's loop)
    tools/delever_search.py --status
    tools/delever_search.py --selftest

WHY. Rung R (`delever --recipes`) is BLIND: it generates ~57 one-move candidates per body, asks the oracle "IDENTICAL?" and throws
everything else away — 134 of 134 on a class whose shape rung D had just found, 0 of 300 where no shape was known (S100, cookbook
§454a): a replication engine, not a discovery engine. Rung D (decomp-permuter) discovers, but as a random walk that reprints the
source. This engine sits between them: the SAME candidate generators, the SAME oracle, but every candidate is SCORED by its masked
mismatch count against the target, the residual is CLASSIFIED to choose the move families, and the search hill-climbs — two- and
three-move compositions guided by the gradient — instead of guessing once.

THE SCORER IS THE ORACLE'S OWN OBJECT. A candidate TU text is compiled through the recipe of ONE object (a header: its first
includer's), the function's instructions are read out of that scratch object (`objdump -drz`, 35 ms on the largest overlay object)
and compared, relocation-masked with reloc-operand equality (`masked_diff.diff_object_object`), with the same function in the fleet
run's baseline object under `build/`. That target is the tree's own bytes — proven by the SHA1 check, carrying the candidates'
relocations by construction — so no listing is assembled, no TU isolated, no cpp expanded (the two instrument classes that cost rung D
two campaigns, §454). Whole-object equality on EVERY recipe of the TU stays the bank verdict (`delever --apply-body`), and the clean
fleet run (R22) gates the batch as it gates every batch of this phase.

THE SEARCH. Beam `B` (3), depth `D` (3), per-node cap `C` (48), budget `M` compiles (400). Node = a TU text with its score and the
move path that made it. Children are generated by the families the residual's class selects (REG on the caller-saved bank → the
commutative swap, the temp inlined/introduced, the initializer split; REG on the callee-saved bank → declaration order/move first;
COUNT → the temp moves; ORDER → the block wrap and the adjacent swap), ranked by score; a child worse than its parent is dropped, a
child with the parent's score and the parent's diff signature (a no-effect move) goes to the tail. The first score-0 child is
verified on every recipe and banked; siblings of its text class are then given the same shape by `delever --propagate`, serially,
after the parallel phase (a sibling lives in a TU another worker may own).

THE CONTROLS (R39/R40/R56), before a yield is believed: every body starts by scoring the tree's OWN text — it must score 0 and be
byte-identical, or the harness is not measuring this function (UNCALIBRATED, recorded); `--positive-control` perturbs a lever-free
MATCHING body by one or two generator moves, requires the perturbed text to score > 0, and requires the search to find its way back to
0 without ever writing the tree; `--selftest` runs the classifier on synthetic instruction streams and the beam on a stub scorer whose
answer needs three composed moves. The evidence of every attempt is `.run/P36/engine/outcomes.jsonl` and a per-body trace under
`.run/P36/engine/trace/` (every scored candidate: the move, the parent's score, its score, its class) — the byte record lane B's
compiler-source hypotheses are checked against.

NEVER RUN A LONG CAMPAIGN AS A HARNESS BACKGROUND TASK (the low-memory guard kills it): `setsid nohup nice -n 10 … &` + a Monitor.
A worker owns a whole translation unit (the oracle writes candidates into the real source path); headers run serially after the TUs.
`pkill -f` never with a literal your own command line contains (R79).
"""
