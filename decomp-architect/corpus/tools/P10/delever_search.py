# --selftest: the classifier on synthetic streams, the beam on a stub scorer whose answer needs three composed moves
# ----------------------------------------------------------------------------------------------------------------------
def _ins(word, reloc_kind=None, reloc_op=None):
    return dict(off=0, word=word, mnem="", reloc_kind=reloc_kind, reloc_op=reloc_op, jrel=None)


def selftest():
    ok = True

    def fail(msg):
        nonlocal ok
        ok = False
        print("selftest:", msg)
    # and v0,v1,v0 (00621024) vs and v0,v0,v1 (00431024): one REG position, caller-saved pairs
    tgt = [_ins(0x8E230044), _ins(0x2402FFDF), _ins(0x00431024)]
    mine = [_ins(0x8E220044), _ins(0x2403FFDF), _ins(0x00621024)]
    c = classify(mine, tgt)
    if c["kind"] != "REG" or c["bank"] != "caller" or c["score"] != 3:
        fail(f"REG-caller classification wrong: {c}")
    # The invariant, not a fixed window (widening the window once per new generator hid what it was for): the temp move
    # leads, and every TARGETED caller-saved lever — R5 the commutative swap, R15 the sink, R16 the constant holder —
    # is drawn before the BLIND families that permute declarations or statements wholesale (R9, R2, R4).
    caller = FAMILIES["REG-caller"]
    # R19 leads (the only family that can change a call's arity, and free when it does not apply), R6 the temp move next,
    # and every TARGETED lever before every BLIND family that permutes declarations or statements wholesale.
    targeted, blind = {"R5", "R15", "R16", "R19"}, {"R9", "R2", "R4"}
    if family_key(c) != "REG-caller" or caller[:2] != ("R19", "R6") or not targeted <= set(caller) \
            or max(caller.index(t) for t in targeted) > min(caller.index(b) for b in blind):
        fail(f"REG-caller family wrong: {family_key(c)} {caller}")
    # a callee-saved swap: addu s0,a0,zero vs addu s1,a0,zero
    c = classify([_ins(0x00808021)], [_ins(0x00808821)])
    if c["kind"] != "REG" or c["bank"] != "callee":
        fail(f"REG-callee classification wrong: {c}")
    # COUNT: one extra move
    c = classify([_ins(0x00808021), _ins(0x8E220044)], [_ins(0x8E220044)])
    if c["kind"] != "COUNT":
        fail(f"COUNT classification wrong: {c}")
    # ORDER: the same two words swapped
    c = classify([_ins(0x8E220044), _ins(0x2403FFDF)], [_ins(0x2403FFDF), _ins(0x8E220044)])
    if c["kind"] != "ORDER":
        fail(f"ORDER classification wrong: {c}")
    # a reloc-masked pair with the same symbol is not a mismatch; a different symbol is
    c = classify([_ins(0x3C040000, "HI16", "D_800A0000")], [_ins(0x3C040000, "HI16", "D_800A0000")])
    if c["kind"] != "IDENTICAL":
        fail(f"masked reloc read as a mismatch: {c}")
    c = classify([_ins(0x3C040000, "HI16", "D_800A0000")], [_ins(0x3C040000, "HI16", "D_800A0004")])
    if c["score"] != 1:
        fail(f"a different reloc symbol not counted: {c}")
    # the beam on a stub: a text is "a,b,c"; the target (2,1,3); score = L1 distance; moves = ±1 on one coordinate, tagged
    # by family so the ranking has something to order; the start (1,0,2) is THREE moves away -> depth 3 must find it
    target = (2, 1, 3)

    def parse(t):
        return tuple(int(x) for x in t.split(","))

    def stub_score(t):
        v = parse(t)
        s = sum(abs(x - y) for x, y in zip(v, target))
        return dict(score=s, ident=(s == 0), cls=dict(kind=("IDENTICAL" if s == 0 else "OTHER"), bank=None, score=s, n_mine=3,
                                                       n_tgt=3, positions=[i for i in range(3) if v[i] != target[i]], pairs=[]),
                    seconds=0.0, err="")

    def stub_gen(t, cls):
        v = parse(t)
        out = []
        for i in range(3):
            for dlt in (1, -1):
                w = list(v)
                w[i] += dlt
                out.append((("R5", "R7", "R2")[i], f"coord{i}{'+' if dlt > 0 else '-'} @{i + 1}", ",".join(map(str, w))))
        return out
    calls = dict(n=0)

    def counting(t):
        calls["n"] += 1
        return stub_score(t)
    res = search("1,0,2", counting, stub_gen, beam=2, depth=3, cap=6, budget=200)
    if res["verdict"] != "MATCH" or len(res["path"]) != 3 or res["compiles"] != calls["n"]:
        fail(f"the beam did not compose three moves: {res}")
    res = search("1,0,2", stub_score, stub_gen, beam=2, depth=2, cap=6, budget=200)
    if res["verdict"] != "NO-MATCH" or res["best"] != 1:
        fail(f"depth 2 should end NO-MATCH at distance 1: {res}")
    res = search("1,0,2", stub_score, stub_gen, beam=2, depth=3, cap=6, budget=4)
    if res["verdict"] != "BUDGET" or res["compiles"] > 4:
        fail(f"the budget did not stop the search: {res}")
    res = search("2,1,3", stub_score, stub_gen)
    if res["verdict"] != "MATCH" or res["compiles"] != 1:
        fail(f"a seed at distance 0 must be MATCH in one score: {res}")
    # the generators on a fixture body: R8 introduces a typed temp, R9 swaps adjacent statements, both through the real parser
    fix = ("s32 f(s32 *p, s32 q)\n{\n    s32 a;\n    s32 b;\n    a = *(s32 *)(p + 4) & q;\n    b = q + 1;\n    return a + b;\n}\n")
    cands = dl.recipe_candidates(fix, "src/x.c", "f", [], cap=None, families=("R8", "R9"))
    r8 = [c for c in cands if c[0] == "R8"]
    r9 = [c for c in cands if c[0] == "R9"]
    temp = [c for c in r8 if c[1].startswith("temp")]
    base = [c for c in r8 if c[1].startswith("base")]
    if len(temp) != 1 or "s32 tmp0;" not in temp[0][2] or "tmp0 = *(s32 *)(p + 4);" not in temp[0][2] or "a = tmp0 & q;" not in temp[0][2]:
        fail(f"R8 did not hoist the dereference into a typed temp: {temp[:1]}")
    if len(base) != 1 or "tmp0 = p + 4;" not in base[0][2] or "a = *(s32 *)tmp0 & q;" not in base[0][2]:
        fail(f"R8 did not hoist the dereference's base into an address local: {base[:1]}")
    if len(r9) != 1 or "    b = q + 1;\n    a = *(s32 *)(p + 4) & q;\n" not in r9[0][2]:
        fail(f"R9 did not swap the two adjacent statements: {r9[:1]}")
    default = dl.recipe_candidates(fix, "src/x.c", "f", [], cap=None)
    if any(c[0] in ("R8", "R9", "R10", "R12", "R13") for c in default):
        fail("rung R's default family set grew — R8..R13 must stay the engine's until measured")
    # R10 on a void-parameter function must yield nothing; on (s32 *p, s32 q) one copy per parameter, pointer spelled `s32 *p2`
    fix2 = ("s32 g(void)\n{\n    s32 d;\n    d = 1;\n    return d;\n}\n")
    if dl.recipe_candidates(fix2, "src/x.c", "g", [], cap=None, families=("R10",)):
        fail("R10 generated a parameter copy for a (void) function")
    r10 = dl.recipe_candidates(fix, "src/x.c", "f", [], cap=None, families=("R10",))
    if len(r10) != 2 or "s32 *p2;" not in r10[0][2] or "p2 = p;" not in r10[0][2] or "*(s32 *)(p2 + 4)" not in r10[0][2]:
        fail(f"R10 parameter copies wrong: {[(c[0], c[1]) for c in r10]}")
    # R12 widens/narrows a local; R13 reassociates a +/- chain; R8 names a repeated RHS once
    fix3 = ("s32 h(s32 *p, s32 q)\n{\n    s32 a;\n    u16 w;\n    a = q + *(s32 *)(p + 4) - w;\n"
            "    *(s16 *)(p + 28) = -a;\n    *(s16 *)(p + 24) = -a;\n    return a;\n}\n")
    r12 = dl.recipe_candidates(fix3, "src/x.c", "h", [], cap=None, families=("R12",))
    if [c[1] for c in r12] != ["width a s32->u16 @3", "width a s32->s16 @3", "width a s32->u8 @3",
                               "width w u16->s32 @4", "width w u16->s16 @4", "width w u16->u8 @4"]:
        fail(f"R12 widths wrong: {[c[1] for c in r12]}")
    # R14 changes a PARAMETER's width in the header; R8's shared base names one address local for two dereferences of one base
    r14 = dl.recipe_candidates(fix3, "src/x.c", "h", [], cap=None, families=("R14",))
    if [c[1] for c in r14] != ["param-width q s32->s16 @1", "param-width q s32->u16 @1", "param-width q s32->u8 @1"] \
            or "s32 h(s32 *p, s16 q)" not in r14[0][2]:
        fail(f"R14 parameter widths wrong: {[c[1] for c in r14]}")
    fix4 = ("s32 m(s32 *p, s32 q)\n{\n    s32 a;\n    a = *(s32 *)(p + 4) & q;\n    *(u16 *)(p + 4) = q;\n    return a;\n}\n")
    sb = [c for c in dl.recipe_candidates(fix4, "src/x.c", "m", [], cap=None, families=("R8",)) if c[1].startswith("base-shared")]
    if len(sb) != 1 or "tmp0 = p + 4;" not in sb[0][2] or "a = *(s32 *)tmp0 & q;" not in sb[0][2] or "*(u16 *)tmp0 = q;" not in sb[0][2]:
        fail(f"R8 shared base wrong: {[(c[1], c[2]) for c in sb][:1]}")
    fix5 = ("s32 k(s32 param_2)\n{\n    u8 *src;\n    src = (u8 *)((u32)param_2);\n    return src[3];\n}\n")
    al = [c for c in dl.recipe_candidates(fix5, "src/x.c", "k", [], cap=None, families=("R10",)) if c[1].startswith("param-alias")]
    if len(al) != 1 or "return param_2[3];" not in al[0][2] or "src = " in al[0][2]:
        fail(f"R10 alias through a cast wrong: {[(c[1], c[2]) for c in al][:1]}")
    r13 = dl.recipe_candidates(fix3, "src/x.c", "h", [], cap=None, families=("R13",))
    if len(r13) != 1 or "a = q - w + *(s32 *)(p + 4);" not in r13[0][2]:
        fail(f"R13 reassociation wrong: {[(c[1], c[2].split(chr(10))[4]) for c in r13]}")
    cse = [c for c in dl.recipe_candidates(fix3, "src/x.c", "h", [], cap=None, families=("R8",)) if c[1].startswith("cse")]
    if len(cse) != 1 or "tmp0 = -a;" not in cse[0][2] or cse[0][2].count("= tmp0;") != 2:
        fail(f"R8 common subexpression wrong: {[(c[1]) for c in cse]}")
    print(f"delever_search --selftest: {'OK' if ok else 'FAILED'} — classifier 6 cases, beam 4 cases, generators R8/R9")
    return ok


def main():
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group(required=True)
    g.add_argument("--plan", action="store_true")
    g.add_argument("--run", action="store_true")
    g.add_argument("--positive-control", nargs=2, metavar=("TU", "FN"))
    g.add_argument("--status", action="store_true")
    g.add_argument("--explain", nargs=2, metavar=("TU", "FN"), help="read one body's residual (no writes)")
    g.add_argument("--try", dest="try_", nargs=3, metavar=("TU", "FN", "FILE"), help="score a candidate TU text (or --body: a body) WITHOUT writing the tree")
    g.add_argument("--selftest", action="store_true")
    ap.add_argument("--path", help="--explain: moves to apply first, `|`-separated, named as the trace names them")
    ap.add_argument("--body", action="store_true", help="--try: FILE holds the function's definition only")
    ap.add_argument("--only", nargs="*", default=[], help="fn, TU (substring), alias or nhash prefix")
    ap.add_argument("--limit", type=int)
    ap.add_argument("--show", type=int, default=25)
    ap.add_argument("--score", action="store_true", help="--plan: score each listed exemplar's lever-free text (one compile each + the control)")
    ap.add_argument("--beam", type=int, default=3)
    ap.add_argument("--depth", type=int, default=3)
    ap.add_argument("--cap", type=int, default=48, help="candidates scored per node")
    ap.add_argument("--budget", type=int, default=400, help="compiles per body")
    ap.add_argument("--moves", type=int, default=1, help="--positive-control: how many perturbing moves")
    ap.add_argument("--seed", type=int, default=1)
    ap.add_argument("--label", default="g1")
    ap.add_argument("--propagate", action=argparse.BooleanOptionalAction, default=True, help="spread each bank to its class (serial, after the run)")
    ap.add_argument("--dirty-ok", action="store_true")
    ap.add_argument("--include-done", action="store_true", help="draw classes that already have an outcome row")
    ap.add_argument("-j", "--jobs", type=int, default=8)
    a = ap.parse_args()
    os.chdir(REPO)
    RUN.mkdir(parents=True, exist_ok=True)
    if a.selftest:
        return 0 if selftest() else 1
    if a.plan:
        return cmd_plan(a)
    if a.status:
        return cmd_status(a)
    if a.explain:
        return explain(a)
    if a.try_:
        return score_file(a)
    if a.positive_control:
        return positive_control(a)
    if a.run:
        return cmd_run(a)


if __name__ == "__main__":
    sys.exit(main())
