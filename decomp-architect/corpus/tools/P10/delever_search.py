def body_span(text, tu, fn):
    d_ = next((r for r in sc.scan_text(text, tu, shared_defs=None) if r["form"] == "def" and r["name"] == fn), None)
    return d_


def rank(cands, fam_order, cls, d_):
    """ROUND-ROBIN across the families in the class's order, locality within a family. A strict family-first order starved
    every later family under the cap: the S101 one-move control was perturbed by one R9 swap and its inverse sat behind 64
    block-wrap candidates, so depth 1 never saw it and the search paid 142 compiles for a two-move detour. Within a family
    the candidates nearest the residual go first (the changed block's index mapped onto the body's lines by fraction — a
    tie-break, never the decider)."""
    est = []
    if cls and cls.get("positions") and d_ and cls["n_mine"]:
        span = d_["end"] - d_["line"]
        est = [d_["line"] + p / cls["n_mine"] * span for p in cls["positions"]]

    def dist(item):
        m = re.search(r"@(\d+)$", item[1])
        return min((abs(int(m.group(1)) - e) for e in est), default=0) if m else 0
    groups = collections.OrderedDict((f, []) for f in fam_order)
    for c in cands:
        groups.setdefault(c[0], []).append(c)
    for g in groups.values():
        g.sort(key=dist)
    out = []
    while any(groups.values()):
        for g in groups.values():
            if g:
                out.append(g.pop(0))
    return out


def search(seed, scorer_fn, gen_fn, beam=3, depth=3, cap=48, budget=400, trace=None, log=None):
    """the beam. scorer_fn(text) -> dict(score, ident, cls, err); gen_fn(text, cls) -> [(rec, desc, text)] ranked.
    Returns dict(verdict, best, start, compiles, path, text, node_cls) — verdict MATCH | NO-MATCH | BUDGET | UNSCORED."""
    s0 = scorer_fn(seed)
    compiles = 1
    if s0["score"] is None:
        return dict(verdict="UNSCORED", best=None, start=None, compiles=compiles, path=[], text=seed, err=s0.get("err", ""))
    if s0["score"] == 0 and s0["ident"]:
        return dict(verdict="MATCH", best=0, start=0, compiles=compiles, path=[], text=seed, node_cls=s0["cls"])
    frontier = [dict(text=seed, score=s0["score"], cls=s0["cls"], path=[])]
    best = frontier[0]
    seen = {seed}
    for d in range(depth):
        children = []
        for parent in frontier:
            psig = signature(parent["cls"])
            cands = gen_fn(parent["text"], parent["cls"])[:cap]
            for rec, desc, ctext in cands:
                if ctext in seen:
                    continue
                seen.add(ctext)
                if compiles >= budget:
                    break
                r = scorer_fn(ctext)
                compiles += 1
                row = dict(depth=d + 1, move=f"{rec} {desc}", parent=parent["score"], score=r["score"],
                           kind=(r["cls"]["kind"] if r["cls"] else r.get("err", "")[:14]), ident=r["ident"])
                if trace is not None:
                    trace.append(row)
                if r["score"] is None:
                    continue
                child = dict(text=ctext, score=r["score"], cls=r["cls"], path=parent["path"] + [f"{rec} {desc}"],
                             noop=(r["score"] == parent["score"] and signature(r["cls"]) == psig))
                if r["score"] == 0 and r["ident"]:
                    if log:
                        log(f"    depth {d + 1}: score 0 by {' + '.join(child['path'])}")
                    return dict(verdict="MATCH", best=0, start=s0["score"], compiles=compiles, path=child["path"],
                                text=ctext, node_cls=r["cls"])
                if r["score"] <= parent["score"]:
                    children.append(child)
            if compiles >= budget:
                break
        if not children:
            break
        children.sort(key=lambda c: (c["score"], c["noop"]))
        if children[0]["score"] < best["score"]:
            best = children[0]
        if log:
            log(f"    depth {d + 1}: {len(children)} kept of the scored, best {children[0]['score']} "
                f"({' + '.join(children[0]['path'])}) · {compiles} compiles")
        frontier = children[:beam]
        if compiles >= budget:
            return dict(verdict="BUDGET", best=best["score"], start=s0["score"], compiles=compiles, path=best["path"],
                        text=best["text"], node_cls=best["cls"])
    return dict(verdict="NO-MATCH", best=best["score"], start=s0["score"], compiles=compiles, path=best["path"],
                text=best["text"], node_cls=best["cls"])


def make_gen(tu, fn, names):
    def gen(text, cls):
        fam = FAMILIES[family_key(cls)] if cls else dl.ALL_FAMILIES
        cands = dl.recipe_candidates(text, tu, fn, names, cap=None, families=fam)
        return rank(cands, fam, cls, body_span(text, tu, fn))
    return gen


