def positive_control(a):
    """perturb a body the tree already matches by one or two generator moves; the search must find its way back to 0.
    Never writes the tree (the scorer restores after every compile; nothing is banked)."""
    tu, fn = a.positive_control
    raw = (REPO / tu).read_text(errors="surrogateescape")
    d_ = body_span(raw, tu, fn)
    if d_ is None:
        sys.exit(f"delever_search --positive-control: {fn} is not defined in {tu}")
    by_src = oracle.recipes_by_src(oracle.load_recipes()["recipes"])
    inc = dl.includers()
    scorer = Scorer(tu, fn, recs_for(tu, by_src, inc), "pc", {})
    ctl = scorer.score(raw)
    print(f"positive control {tu}:{fn}: the tree's own text scores {ctl['score']} ident={ctl['ident']}", flush=True)
    if ctl["score"] != 0 or not ctl["ident"]:
        sys.exit("delever_search --positive-control: the UNPERTURBED body does not score 0 — calibrate/build first (R56)")
    names = dl.pin_names(sites_by_body().get((tu, fn), []))
    gen = make_gen(tu, fn, names)
    text, moves = raw, []
    rng = random.Random(a.seed)
    for k in range(a.moves):
        cands = dl.recipe_candidates(text, tu, fn, names, cap=None, families=dl.ALL_FAMILIES)
        rng.shuffle(cands)
        picked = None
        for rec, desc, ctext in cands[:40]:
            r = scorer.score(ctext)
            if r["score"] is not None and r["score"] > 0 and (k == 0 or r["score"] != scorer.score(text)["score"]):
                picked = (rec, desc, ctext, r["score"])
                break
        if picked is None:
            sys.exit(f"delever_search --positive-control: no generator move perturbs {fn} at step {k + 1} — pick another body")
        moves.append(f"{picked[0]} {picked[1]}")
        text = picked[2]
        print(f"  perturbed by {moves[-1]} -> score {picked[3]}", flush=True)
    trace = []
    res = search(text, scorer.score, gen, beam=a.beam, depth=a.depth, cap=a.cap, budget=a.budget, trace=trace,
                 log=lambda m: print(m, flush=True))
    ok = res["verdict"] == "MATCH"
    print(f"positive control: {'PASS' if ok else 'FAIL'} — perturbed by {' + '.join(moves)} (start {res.get('start')}), "
          f"{res['verdict']} after {res['compiles']} compiles" + (f" by {' + '.join(res['path'])}" if ok else f" (best {res.get('best')})"))
    outcome_append(dict(kind="positive-control", ts=time.strftime("%Y-%m-%d %H:%M:%S"), tu=tu, fn=fn, moves=moves,
                        verdict=res["verdict"], start=res.get("start"), compiles=res["compiles"], path=res.get("path", []),
                        seconds=round(scorer.seconds, 1)))
    return 0 if ok else 1


