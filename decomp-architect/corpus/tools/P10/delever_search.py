def run_body(ex, a, tag, by_src, inc, inflight, log):
    tu, fn = ex["tu"], ex["fn"]
    t0 = time.time()
    row = dict(kind="attempt", ts=time.strftime("%Y-%m-%d %H:%M:%S"), label=a.label, nhash=ex["nhash"], tu=tu, fn=fn,
               alias=ex["alias"], copies=ex["copies"], needed=ex["needed"], kinds=ex["kinds"], regs=ex.get("regs", []),
               beam=a.beam, depth=a.depth, cap=a.cap, budget=a.budget)
    sites = sites_by_body().get((tu, fn), [])
    raw = (REPO / tu).read_text(errors="surrogateescape")
    try:
        if not sites:
            raise Unstrippable([("<census>", 0, "no site in the census for this body (stale? rerun lever_census --sites)")])
        free = lever_free_body(tu, raw, fn, sites)
        scorer = Scorer(tu, fn, recs_for(tu, by_src, inc), tag, inflight)
    except Unstrippable as u:
        row.update(verdict="UNSTRIPPABLE", why=u.args[0][:4], seconds=round(time.time() - t0, 1))
        outcome_append(row)
        log(f"  {ex['alias']}__{fn}: UNSTRIPPABLE — {u.args[0][:2]}")
        return row
    # THE CONTROL (R56): the tree's own text must score 0 AND be byte-identical, or this harness is not measuring this function
    ctl = scorer.score(raw)
    if ctl["score"] != 0 or not ctl["ident"]:
        row.update(verdict="UNCALIBRATED", control=dict(score=ctl["score"], ident=ctl["ident"], err=ctl.get("err", "")),
                   seconds=round(time.time() - t0, 1))
        outcome_append(row)
        log(f"  {ex['alias']}__{fn}: UNCALIBRATED — the tree's own text scores {ctl['score']} ident={ctl['ident']} {ctl.get('err', '')[:80]}")
        return row
    names = dl.pin_names(sites)
    trace = []
    res = search(free, scorer.score, make_gen(tu, fn, names), beam=a.beam, depth=a.depth, cap=a.cap, budget=a.budget,
                 trace=trace, log=log)
    if res["verdict"] == "MATCH":
        # the bank verdict: every recipe of the file, then the proven apply path (the ledger row with before/after text)
        v, dt, err = scorer.verify_all(res["text"])
        body = None
        if v != "IDENTICAL":
            res["verdict"] = "ONE-OBJECT-ONLY"                # R34: the one-object score said 0, the file's other objects disagree
            row["verify"] = f"{v} {err[:120]}"
        else:
            d_ = body_span(res["text"], tu, fn)
            ls = dl.line_starts(res["text"])
            body = res["text"][ls[d_["line"] - 1]:ls[d_["end"]]]
            # THE BANK IS BODY-ONLY (apply_body_core splices the definition; --propagate remaps that body to siblings), so
            # a candidate that also edited lines outside the definition verifies at 0 and can never be banked. Say so in
            # its own words instead of letting the bank fail on `conflicting types` (S102 run s4, func_80136824: 288
            # compiles to a real score 0, then a BANK-REFUSED that read like a bad body). R14 no longer generates these.
            d0 = body_span(free, tu, fn)
            l0 = dl.line_starts(free)
            outside_now = res["text"][:ls[d_["line"] - 1]] + res["text"][ls[d_["end"]]:]
            outside_before = free[:l0[d0["line"] - 1]] + free[l0[d0["end"]]:]
            if outside_now != outside_before:
                res["verdict"] = "OUT-OF-BODY"
                row["verify"] = "the candidate edits lines outside the definition; the bank is body-only"
                body = None
        if res["verdict"] == "MATCH" and body is not None:
            bf = RUN / "bodies" / f"{(ex['alias'] or 'x')}__{fn}.c"
            bf.parent.mkdir(parents=True, exist_ok=True)
            bf.write_text(body, errors="surrogateescape")            # the record of what was handed to the bank
            # IN PROCESS (S101): the bank used to be a subprocess that re-imported delever.py (an edit mid-run broke a bank)
            # and reloaded the recipes/includers each time
            with _LOCK:                                            # the ledger append and the source write, one bank at a time
                ok_, line = dl.apply_body_core(tu, fn, body, a.label, "G", source=bf.relative_to(REPO).as_posix())
            row["banked"] = ok_
            row["bank_line"] = line[:220]
            if not ok_:
                res["verdict"] = "BANK-REFUSED"
    row.update(verdict=res["verdict"], start=res.get("start"), best=res.get("best"), compiles=res["compiles"],
               path=res.get("path", []), start_cls=(trace and None) or None, seconds=round(time.time() - t0, 1),
               oracle_seconds=round(scorer.seconds, 1))
    if res.get("node_cls"):
        row["best_cls"] = {k: v for k, v in res["node_cls"].items() if k != "positions"}
    if trace:
        TRACE.mkdir(parents=True, exist_ok=True)
        with open(TRACE / f"{(ex['alias'] or 'x')}__{fn}.jsonl", "w") as f:
            f.write(json.dumps(dict(kind="seed", start=res.get("start"), tu=tu, fn=fn, label=a.label)) + "\n")
            for t in trace:
                f.write(json.dumps(t) + "\n")
    outcome_append(row)
    log(f"  {ex['alias']}__{fn}: {row['verdict']} start={row['start']} best={row['best']} compiles={row['compiles']} "
        f"({row['seconds']}s, {ex['copies']} copies, {ex['needed']} needed"
        + (f", {' + '.join(row['path'])}" if row['path'] else "") + ")")
    return row


def cmd_run(a):
    dl.ensure_census(a.jobs)
    ok, why = oracle.calibration_current()
    if not ok:
        sys.exit(f"delever_search --run: calibration not current ({why})")
    clean, dirty = dl.src_clean()
    if not clean and not a.dirty_ok:
        sys.exit(f"delever_search --run: src/ is dirty (commit or --restore first):\n{dirty[:400]}")
    by_src = oracle.recipes_by_src(oracle.load_recipes()["recipes"])
    inc = dl.includers()
    ex = exemplars(a.only, a.limit, a.include_done)
    if not ex:
        print("delever_search --run: no drawable exemplar (every class attempted, or --only matched none) (R68)")
        return 1
    inflight = {}
    RUN.mkdir(parents=True, exist_ok=True)
    print(f"delever_search --run: {len(ex)} exemplars ({sum(e['copies'] for e in ex):,} bodies behind them), {a.jobs} worker(s), "
          f"beam {a.beam} × depth {a.depth} × cap {a.cap}, budget {a.budget} compiles per body, label {a.label}", flush=True)
    t0 = time.time()

    def log(msg):
        print(msg, flush=True)
    # a worker owns a whole TU: exemplars grouped by TU; headers serial after the TUs
    by_tu = collections.OrderedDict()
    for e in ex:
        by_tu.setdefault(e["tu"], []).append(e)
    # BOTTOM-UP WITHIN A FILE (rung R's rule): a bank shifts the lines of every body below it, and the census positions the
    # lever-free rewrite starts from were taken before the run — run g1 lost func_80142EC0 to a `token mismatch` after
    # func_801424E4 was banked above it in the same TU
    sb = sites_by_body()
    for tu in by_tu:
        by_tu[tu].sort(key=lambda e: -min((s["line"] for s in sb.get((e["tu"], e["fn"]), [])), default=0))
    tus = [t for t in by_tu if not t.endswith(".h")]
    hdrs = [t for t in by_tu if t.endswith(".h")]
    rows = []

    def work(item):
        n, tu = item
        return [run_body(e, a, f"g{n % max(1, a.jobs)}", by_src, inc, inflight, log) for e in by_tu[tu]]
    with ThreadPoolExecutor(max_workers=max(1, a.jobs)) as pool:
        for res in pool.map(work, list(enumerate(tus))):
            rows += res
    for tu in hdrs:
        rows += work((0, tu))
    won = [r for r in rows if r["verdict"] == "MATCH" and r.get("banked")]
    # propagation, serially after the parallel phase: a sibling lives in a TU another worker may have owned
    if a.propagate and won:
        for r in won:
            ns = argparse.Namespace(propagate=[r["tu"], r["fn"]], label=a.label + "p", only=[], limit=None)
            try:
                okn, n, bad = dl.propagate(ns)                     # in process (S101): no subprocess per sibling
                line = f"delever --propagate: {okn} of {n} sibling(s) banked, {bad} refused"
                rc = 0 if okn else 1
            except SystemExit as e:                               # "no banked reshape" — the refusal is the line
                line, rc = str(e), 2
            r["propagate_line"] = line[:200]
            outcome_append(dict(kind="propagate", ts=time.strftime("%Y-%m-%d %H:%M:%S"), label=a.label, tu=r["tu"], fn=r["fn"],
                                nhash=r["nhash"], line=line[:300], rc=rc))
            log(f"  propagate {r['alias']}__{r['fn']}: {line[:160]}")
    v = collections.Counter(r["verdict"] for r in rows)
    print(f"\nsearch: {len(won)} of {len(rows)} exemplars matched lever-free in {(time.time() - t0) / 3600:.2f} h "
          f"({sum(r['copies'] for r in won):,} of {sum(r['copies'] for r in rows):,} bodies behind them; "
          f"{sum(r.get('compiles', 0) for r in rows):,} compiles) — " + " · ".join(f"{k} {n}" for k, n in v.most_common()))
    return 0


