def matches(ex, only):
    if not only:
        return True
    return any(o == ex["fn"] or o == ex["tu"] or o in ex["tu"] or (ex["nhash"] or "").startswith(o) or o == ex["alias"] for o in only)


def exemplars(only=(), limit=None, include_done=False):
    """one exemplar per RESIDUE text class of the delever ledger, largest class first, then fewest NEEDED sites."""
    cur, order = {}, []
    for r in dl.load_ledger():
        k = (r.get("tu"), r.get("fn"))
        if not k[0] or not k[1]:
            continue
        if k not in cur:
            order.append(k)
        cur[k] = r
    groups = collections.OrderedDict()
    nohash = 0
    for k in order:
        r = cur[k]
        if r.get("verdict") != "RESIDUE" or r["fn"] == dl.FILE_SCOPE_FN:
            continue
        # THE PHASE'S NUMBER is pins + asm statements: a body whose only NEEDED sites are class C/D (a byte-needed `volatile`, a bare
        # `register`) is done (decision 3) and is not drawn — the T4 close counted 498 such bodies, and g3 spent searches on them
        if not any(s.get("verdict") == "NEEDED" and s.get("kind") in AB_KINDS for s in r.get("sites", [])):
            continue
        nh = r.get("nhash_after") or r.get("nhash_before")
        if not nh:
            nohash += 1
            continue
        groups.setdefault(nh, []).append((k, r))
    if nohash:
        sys.exit(f"delever_search: {nohash} RESIDUE row(s) carry no text hash — run `tools/delever.py --repair-nhash` first (R43)")
    done = set() if include_done else {o["nhash"] for o in load_outcomes() if o.get("kind") == "attempt"}
    out = []
    for nh, members in groups.items():
        if nh in done:
            continue
        (tu, fn), r = members[0]
        needed = [s for s in r.get("sites", []) if s.get("verdict") == "NEEDED"]
        out.append(dict(nhash=nh, tu=tu, fn=fn, alias=(r.get("aliases") or [None])[0], copies=len(members), needed=len(needed),
                        kinds=sorted({s["kind"] for s in needed}), regs=sorted({s.get("detail", "") for s in needed if s["kind"] == "pin"}),
                        members=[dict(tu=t, fn=f) for (t, f), _ in members], row=r))
    out.sort(key=lambda e: (-e["copies"], e["needed"], e["tu"], e["fn"]))
    out = [e for e in out if matches(e, only)]
    return out[:limit] if limit else out


def recs_for(tu, by_src, inc):
    return [r for t_ in inc.get(tu, []) for r in by_src.get(t_, [])] if tu.endswith(".h") else by_src.get(tu, [])


