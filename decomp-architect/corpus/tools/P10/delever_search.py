# the residual's class, from two instruction streams
# ----------------------------------------------------------------------------------------------------------------------
def shape(i):
    """the instruction with its register fields zeroed (a reloc-masked immediate too) — two words of one shape differ only
    in which registers they name."""
    w, kind = i["word"], i["reloc_kind"]
    op = w >> 26
    if op == 0:
        return ("R", w & 63, (w >> 6) & 31)
    if op in (2, 3):
        return ("J", op, i.get("reloc_op") or "")
    if op == 18:                                          # cop2: rs = the sub-op, rt = the CPU register, the rest cop fields
        return ("C", w & ~(31 << 16))
    return ("I", op, (w & 0xFFFF) if kind is None else ("rel", i.get("reloc_op") or ""))


def regs_of(i):
    w = i["word"]
    op = w >> 26
    if op == 0:
        return ((w >> 21) & 31, (w >> 16) & 31, (w >> 11) & 31)
    if op in (2, 3):
        return ()
    if op == 18:
        return ((w >> 16) & 31,)
    return ((w >> 21) & 31, (w >> 16) & 31)


def masked_word(i):
    """the comparable form of one instruction: the reloc-masked word, the reloc operand (symbol+addend) and an internal `j`'s
    target — equality of two streams of these ⟺ masked_diff.diff_object_object == 0 (the same rule, R33)."""
    return (i["word"] & md.mask_for(i["word"], i["reloc_kind"]), i.get("reloc_op") or "", i.get("jrel"))


def classify(mine, tgt):
    """dict(kind, bank, score, n_mine, n_tgt, positions, pairs) — kind in REG | COUNT | ORDER | MIXED | OTHER | IDENTICAL;
    bank (REG only) in caller | callee | mixed, from the register pairs that differ.

    THE SCORE IS AN EDIT DISTANCE, NOT A POSITIONAL COUNT. The positional mismatch count (`match_one`'s closeness) reads a
    one-instruction shift as "everything after it" — the two-move positive control at S101 read 43 for one inlined temp — so a
    hill-climb on it cannot see that a candidate moved the residual from 43 shifted words to 2 real ones. difflib's opcodes over
    the masked words give the real delta (insertions, deletions, replaced blocks); a replace block whose words keep their shape
    (opcode, immediate, function code) and change only their register fields is the REG class."""
    a, b = [masked_word(i) for i in mine], [masked_word(i) for i in tgt]
    if a == b:
        return dict(kind="IDENTICAL", bank=None, score=0, n_mine=len(mine), n_tgt=len(tgt), positions=[], pairs=[])
    ops = [op for op in difflib.SequenceMatcher(None, a, b, autojunk=False).get_opcodes() if op[0] != "equal"]
    score = sum(max(i2 - i1, j2 - j1) for _, i1, i2, j1, j2 in ops)
    pos = [i for _, i1, i2, _, _ in ops for i in range(i1, max(i2, i1 + 1))]
    pairs = collections.Counter()
    count = any(t in ("insert", "delete") or (i2 - i1) != (j2 - j1) for t, i1, i2, j1, j2 in ops)
    n_rep = n_reg = 0
    for t, i1, i2, j1, j2 in ops:
        if t != "replace" or (i2 - i1) != (j2 - j1):
            continue
        for k in range(i2 - i1):
            n_rep += 1
            if shape(mine[i1 + k]) == shape(tgt[j1 + k]):
                n_reg += 1
                for x, y in zip(regs_of(mine[i1 + k]), regs_of(tgt[j1 + k])):
                    if x != y:
                        pairs[(x, y)] += 1
    if len(a) == len(b) and sorted(a) == sorted(b):
        kind = "ORDER"                                    # a pure reorder reads as delete+insert to difflib: test it first
    elif count:
        kind = "COUNT"
    elif n_rep and n_reg == n_rep:
        kind = "REG"
    else:
        kind = "MIXED" if n_reg else "OTHER"
    regs = {x for x, _ in pairs} | {y for _, y in pairs}
    bank = None
    if kind == "REG":
        callee, caller = bool(regs & CALLEE), bool(regs & CALLER)
        bank = "mixed" if callee and caller else "callee" if callee else "caller"
    return dict(kind=kind, bank=bank, score=score, n_mine=len(mine), n_tgt=len(tgt), positions=pos[:24],
                pairs=[(REGNAME.get(x, x), REGNAME.get(y, y), n) for (x, y), n in pairs.most_common(8)])


def family_key(cls):
    if cls["kind"] == "REG":
        return f"REG-{cls['bank']}"
    return cls["kind"] if cls["kind"] in FAMILIES else "OTHER"


def signature(cls):
    """what the diff looks like, independent of the text that produced it — two candidates with one signature moved nothing
    relative to each other."""
    return (cls["kind"], cls["n_mine"], tuple(cls["positions"]), tuple(cls["pairs"]))


# ----------------------------------------------------------------------------------------------------------------------
# the scorer: one compile through the oracle's recipe, the function's instructions against the baseline object's
# ----------------------------------------------------------------------------------------------------------------------
class Scorer:
    def __init__(self, tu, fn, recs, tag, inflight):
        if not recs:
            raise Unstrippable([("<recipe>", 0, f"no recipe compiles {tu}")])
        self.tu, self.fn, self.recs, self.tag = tu, fn, recs, tag
        self.primary = recs[0]
        self.header = tu.endswith(".h")
        self.path = REPO / tu
        self.inflight = inflight
        base = oracle.baseline_path(self.primary["obj"])   # the snapshot when one exists: `make clean` must not wipe a live score
        if not base.exists():
            raise Unstrippable([("<baseline>", 0, f"{self.primary['obj']} missing — run the fleet build first (R56)")])
        self.base_bytes = base.read_bytes()
        dump = subprocess.run([md.OBJDUMP, "-drz", "-j", ".text", str(base)], capture_output=True, text=True).stdout
        if f"<{fn}>:" not in dump:
            raise Unstrippable([("<baseline>", 0, f"{fn} is not a label of {self.primary['obj']}")])
        self.tgt = md.insns_from_object(str(base), fn)
        self.compiles = 0
        self.seconds = 0.0
        OBJ.mkdir(parents=True, exist_ok=True)
        # PER TU, not per tag (S101 run g4s): the tag was the TU's index modulo the worker count, not a worker id, so two
        # TUs could share `g0.o` at the same moment and one worker objdumped the other's object — a byte-identical body read
        # as 14,871 mismatches (UNCALIBRATED), and any candidate scored in that window was noise. A worker owns a whole TU,
        # so a name keyed by the TU cannot collide. The bank was never at risk: it re-verifies whole-object equality itself.
        self.scratch = OBJ / f"{tag}__{tu.replace('/', '_')}.o"

    def score(self, text):
        """dict(score, ident, cls, seconds, err) — score None on a compile failure (R61: not judged is not a distance)."""
        raw, st = self.path.read_text(errors="surrogateescape"), self.path.stat()
        with _LOCK:
            self.inflight[self.tu] = raw
            dl.INFLIGHT.write_text(json.dumps(self.inflight))
        try:
            data, dt, err = oracle.compile_obj(self.primary, text, tag=self.tag, write_path=(self.tu if self.header else None))
        finally:
            dl.restore_file(self.path, raw, st)
            with _LOCK:
                self.inflight.pop(self.tu, None)
                if self.inflight:
                    dl.INFLIGHT.write_text(json.dumps(self.inflight))
                else:
                    dl.INFLIGHT.unlink(missing_ok=True)
        self.compiles += 1
        self.seconds += dt
        if data is None:
            return dict(score=None, ident=False, cls=None, seconds=dt,
                        err=("COMPILE-CRASH" if err.startswith("CRASH:") else "COMPILE-ERROR") + ": " + err[:120])
        p = self.scratch
        p.write_bytes(data)
        mine = md.insns_from_object(str(p), self.fn)
        cls = classify(mine, self.tgt)
        return dict(score=cls["score"], ident=(data == self.base_bytes), cls=cls, seconds=dt, err="")

    def verify_all(self, text):
        """the bank verdict: IDENTICAL on every recipe of the file (a twin's object; every includer of a header)."""
        raw, st = self.path.read_text(errors="surrogateescape"), self.path.stat()
        try:
            return oracle.judge_all(self.recs, text, tag=self.tag + "v", write_path=(self.tu if self.header else None))
        finally:
            dl.restore_file(self.path, raw, st)


