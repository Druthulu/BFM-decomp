#!/usr/bin/env python3
"""rename_sym.py — apply symbol renames: symbol files, token rewrite, names ledger row (P3.42 T3).

  rename_sym.py --spec TSV --task T<n> [--dry-run]

Spec TSV (tab, header line): old new addr binary kind basis confidence evidence conflict citation.
  binary  an alias (main, resident, ov_SC01_077, ...) or `class:<config/dedup.us.yaml id>`: one row per
          member (old = member name, addr = member vram; the `vram:` + `binaries:` group form is one member per
          binary named by its `func`); members in one binary get distinct names new, new_2, new_3 in vram
          order, numbered per (new, binary) across the whole spec.
Before any write, every names row it would write is validated with rename_scan.row_errors (kind func/data
only); a rejected row exits 1 with nothing written.
Per planned row:
  1. its symbol file (main -> config/symbols.us.txt, else config/symbols.<alias>.txt): the line naming old
     is renamed; a placeholder old (func_/D_<ADDR>) with no line gets one, in address order, and the
     `// count=N` header is updated.
  2. `\\bold\\b` is rewritten in every tracked text file except rename_scan.HISTORY paths, generated files
     (first 3 lines say `generated by tools/<x>`, or a path under GENERATED), config/names.tsv, the spec
     itself, and header-file tokens `func_<ADDR>(__\\w+)?.h` (share headers are named by vram, never renamed).
     A generated file that mentions old prints `regenerate: <cmd>` instead (the header's `regenerate:`
     command, else its generator), except rename_scan.TEXT_GENERATED files, which are rewritten as text.
  3. config/names.tsv: per spec row (a class row is ONE row, scope `class:<id>`) name=new, scope=the
     symbol file's alias (`us` for main: what rename_scan --ledger accepts), tier guess iff new starts
     guess_. The row matched by (old, scope) is rewritten in place (a re-rename); else a row is appended.
     history gains `<old> (<phase> <task>)`, `; `-joined; phase from phase-ends/current/PHASE_PLAN.md line 1.
  4. restruct's name-keyed ledger (tools/restruct.py:107, .run/P37/restruct/ledger.jsonl): rows whose
     `fn` is old get new; the count is printed.
Then prints the touched binaries (symbol-file owners, binaries of rewritten src/ files, binaries whose asm/
mentions old), their tracked Ghidra programs (config/ghidra/ROSTER.md) and the regenerate commands.
Verify with tools/rename_scan.py --spec TSV after `make extract` + gates. --dry-run writes nothing.
The planner (parse_spec, expand, edit_symbols, plan, update_names, prepare, regen_cmd, groups_from_registry)
is pure; rename_scan --selftest covers it.
"""
import argparse, json, os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lint_symbol_refs as lsr      # the ONE symbol-file parser
import rename_scan as rs            # HISTORY, COLUMNS, PLACEHOLDER, NAMES_TSV

REPO = lsr.REPO
SPEC_COLS = ("old", "new", "addr", "binary", "kind", "basis", "confidence", "evidence", "conflict", "citation")
REGISTRY = "config/dedup.us.yaml"
# the card's generated list (HOW_WE_WORK.md "Generated"): path prefix -> regenerate command
GENERATED = {"asm/": "make extract BINARY=<alias>", "extracted/": "make extract BINARY=<alias>",
             "assets/": "make extract BINARY=<alias>", "build/": "make check BINARY=<alias>",
             "docs/tool-index.md": "make kit-corpus",
             "config/ghidra/types/": "/usr/bin/python3 tools/ghidra_types.py --write"}
REPORT_GENERATORS = ("tools/progress.py", "tools/dup_report.py", "tools/difficulty.py")   # Makefile `report`
GHIDRA = {"main": "SLUS_007.26", "resident": "resident", "ov_SC01_077": "ov_SC01_077",
          "ov_SC06_018": "ov_SC06_018"}    # config/ghidra/ROSTER.md:10-17 (the proto programs hold no game names)
RESTRUCT_LEDGER = ".run/P37/restruct/ledger.jsonl"    # tools/restruct.py:107 LEDGER
PHASE_PLAN = "phase-ends/current/PHASE_PLAN.md"         # line 1 `# Phase <id> ...`: the history stamp's phase
GEN_RE = re.compile(r"generated by (tools/[\w./-]+)([^)\n]*)")


# ---------------------------------------------------------------- planner (pure)
def parse_spec(text):
    """-> [dict per SPEC_COLS]. Header line required; # comments and blank lines skipped."""
    rows, header = [], None
    for ln in text.splitlines():
        if not ln.strip() or ln.startswith("#"):
            continue
        f = ln.split("\t")
        if header is None:
            if tuple(f) != SPEC_COLS:
                raise ValueError("spec header must be: " + "\\t".join(SPEC_COLS))
            header = f
            continue
        if len(f) != len(SPEC_COLS):
            raise ValueError("spec row has %d fields, needs %d: %r" % (len(f), len(SPEC_COLS), ln))
        rows.append(dict(zip(SPEC_COLS, f)))
    return rows


def symbol_file(alias):
    return "config/symbols.us.txt" if alias == "main" else "config/symbols.%s.txt" % alias


def file_alias(alias):
    return "us" if alias == "main" else alias


def _addr(a):
    return "0x%08X" % int(a, 16)


def _hex(v):
    """A registry vram -> '0x%08X'. YAML reads a bare 0x80179B28 as the int 2149030696: never str() it."""
    return "0x%08X" % (v if isinstance(v, int) else int(str(v), 16))


def expand(rows, groups):
    """groups = {id: [{binary, vram, name}]}. -> one row per (row, member), tagged `cls`=id; members get new,
    new_2, ... in vram order, numbered per (new, binary) across the WHOLE spec (two class rows with one new
    name stay distinct). Plain rows pass through with a normalized addr."""
    out, n = [], {}
    for r in rows:
        b = r["binary"]
        if not b.startswith("class:"):
            out.append(dict(r, addr=_addr(r["addr"])))
            continue
        gid = b[len("class:"):]
        if gid not in groups:
            raise ValueError("no registry group %r" % gid)
        for m in sorted(groups[gid], key=lambda m: (m["binary"], int(_hex(m["vram"]), 16))):
            k = n[(r["new"], m["binary"])] = n.get((r["new"], m["binary"]), 0) + 1
            out.append(dict(r, old=m["name"], addr=_hex(m["vram"]), binary=m["binary"], cls=gid,
                            new=r["new"] if k == 1 else "%s_%d" % (r["new"], k)))
    return out


def edit_symbols(text, old, new, addr, kind):
    """-> text with old renamed to new on its line, or (placeholder old, no line) a new line in address
    order plus the `// count=N` header bumped. Raises on a conflict."""
    lines = text.split("\n")
    want = int(addr, 16)
    at, insert = None, None
    for i, ln in enumerate(lines):
        for nm, ad in lsr.iter_symbol_defs(ln):
            if nm == new:
                raise ValueError("%s already defined" % new)
            if nm == old:
                at = i
            elif int(ad, 16) == want and re.search(r"//\s*%s\b" % kind, ln):
                raise ValueError("0x%08X already named %s" % (want, nm))
            if insert is None and int(ad, 16) > want:
                insert = i
    if at is not None:
        lines[at] = re.sub(r"^%s\s*=" % re.escape(old), "%-32s =" % new, lines[at])
        return "\n".join(lines)
    if not rs.PLACEHOLDER.match(old):
        raise ValueError("%s has no symbol line and is not a placeholder" % old)
    new_ln = "%-32s = %s; // %s" % (new, addr, kind)
    if insert is None:                                 # after the last definition
        insert = max((i for i, ln in enumerate(lines) if list(lsr.iter_symbol_defs(ln))), default=len(lines) - 1) + 1
    lines.insert(insert, new_ln)
    for i, ln in enumerate(lines):
        m = re.match(r"^(//\s*count=)(\d+)\s*$", ln)
        if m:
            lines[i] = m.group(1) + str(int(m.group(2)) + 1)
            break
    return "\n".join(lines)


def plan(rows, groups, symtexts):
    """symtexts = {symbol-file path: text}. -> (planned rows with `symfile`, {path: new text}). Pure."""
    planned, texts = [], dict(symtexts)
    names = set()
    for r in expand(rows, groups):
        if (r["new"], r["binary"]) in names:
            raise ValueError("duplicate new name %s in %s" % (r["new"], r["binary"]))
        names.add((r["new"], r["binary"]))
        p = symbol_file(r["binary"])
        if p not in texts:
            raise ValueError("no symbol file %s for binary %s" % (p, r["binary"]))
        texts[p] = edit_symbols(texts[p], r["old"], r["new"], r["addr"], r["kind"])
        planned.append(dict(r, symfile=p))
    return planned, {p: t for p, t in texts.items() if t != symtexts.get(p)}


def rewrite_re(old):
    return re.compile(r"\b%s\b(?!(?:__\w+)?\.h\b)" % re.escape(old))


def names_fields(r, groups):
    """spec row -> its names.tsv row (dict per rs.COLUMNS, history = old until update_names stamps it).
    A class row is ONE row, scope `class:<id>`, addr = the spec addr or else the lowest member vram."""
    b = r["binary"]
    if b.startswith("class:"):
        scope = b
        try:
            addr = _addr(r["addr"])
        except ValueError:
            addr = min((_hex(m["vram"]) for m in groups.get(b[len("class:"):], ())), default="-")
    else:
        scope, addr = file_alias(b), _addr(r["addr"])
    tier = "guess" if r["new"].startswith("guess_") else "cited"
    return dict(name=r["new"], kind=r["kind"], scope=scope, addr=addr, tier=tier, basis=r["basis"],
                confidence=r["confidence"], evidence=r["evidence"], conflict=r["conflict"], history=r["old"],
                citation=r["citation"])


def names_row(v):
    return "\t".join(v[c] for c in rs.COLUMNS)


def update_names(text, rows, stamp):
    """text = config/names.tsv; rows = names_fields dicts. A row whose (old, scope) names an existing row
    rewrites that row and appends `<old> (<stamp>)` to its history (`; `-joined); any other is appended with
    history `<old> (<stamp>)`. Pure. -> (new text, the written row dicts)."""
    lines = text.split("\n")
    hi = rs.COLUMNS.index("history")
    at = {}
    for i, ln in enumerate(lines):
        f = ln.split("\t")
        if ln.startswith("#") or len(f) != len(rs.COLUMNS) or tuple(f) == rs.COLUMNS:
            continue
        at[(f[0], f[2])] = i
    added, written = [], []
    for v in rows:
        h = "%s (%s)" % (v["history"], stamp)
        i = at.pop((v["history"], v["scope"]), None)
        if i is None:
            v = dict(v, history=h)
            added.append(names_row(v))
        else:
            prev = lines[i].split("\t")[hi]
            v = dict(v, history=h if prev in ("", "-") else prev + "; " + h)
            lines[i] = names_row(v)
            at[(v["name"], v["scope"])] = i
        written.append(v)
    out = "\n".join(lines)
    if added:
        out = out.rstrip("\n") + "\n" + "\n".join(added) + "\n"
    return out, written


def prepare(rows, groups, symtexts, names_text, aliases, stamp):
    """Everything main writes, computed before any write. Pure. -> (planned, {symbol file: text},
    new names.tsv text, written names rows). Raises ValueError (nothing written) on a planner conflict or
    a names row rs.row_errors rejects (or of a kind other than func/data)."""
    planned, newtexts = plan(rows, groups, symtexts)
    ntext, nrows = update_names(names_text, [names_fields(r, groups) for r in rows], stamp)
    errs = []
    for v in nrows:
        e = rs.row_errors(v, aliases, groups) + ([] if v["kind"] in ("func", "data") else ["kind"])
        if e:
            errs.append("%s (%s): %s" % (v["name"], v["scope"], ", ".join(e)))
    if errs:
        raise ValueError("names row(s) rejected, nothing written: " + "; ".join(errs))
    return planned, newtexts, ntext, nrows


def phase_of(plan_text):
    m = re.match(r"# Phase (\S+)", plan_text)
    if not m:
        raise ValueError("%s line 1 is not `# Phase <id> ...`" % PHASE_PLAN)
    return m.group(1)


def regen_cmd(path, head):
    """-> the regenerate command when path is generated, else None (also for rs.TEXT_GENERATED: those are
    rewritten as text). The command is the header's `regenerate: <cmd>` (up to `-->`, `)` or EOL), else the
    generator alone."""
    if path in rs.TEXT_GENERATED or path.startswith(("src/", "include/")):
        return None    # build inputs are always rewritten (3.43 T2: cls_*.h carry a share_body.py marker)
    for pre, cmd in GENERATED.items():
        if path.startswith(pre):
            parts = path.split("/")
            return cmd.replace("<alias>", parts[1] if pre == "asm/" and len(parts) > 2 else "main")
    m = GEN_RE.search(head)
    if not m:
        return None
    if m.group(1) in REPORT_GENERATORS:
        b = re.search(r"\.((?:ov|md)_\w+|resident)\.md$", path)
        return "make report BINARY=%s" % (b.group(1) if b else "main")
    g = re.search(r"regenerate:\s*(.+?)\s*(?:-->|\)|$)", head, re.M)
    return g.group(1) if g else "/usr/bin/python3 %s" % m.group(1)


# ---------------------------------------------------------------- apply
def _git(*args):
    return subprocess.run(("git",) + args, cwd=REPO, capture_output=True, text=True, check=True).stdout


def groups_from_registry(d):
    """Pure. Parsed registry -> ({id: [{binary, vram '0x%08X', name}]}, groups with `members` filled in).
    The `vram:` + `binaries:` form gives one member per binary, named g["func"]."""
    out, reg = {}, []
    for g in d.get("groups", []):
        if "members" in g:
            ms = [dict(m, vram=_hex(m["vram"])) for m in g["members"]]
        else:
            ms = [{"binary": b, "vram": _hex(g["vram"]), "name": g["func"]} for b in g.get("binaries", [])]
        out[g["id"]] = ms
        reg.append(dict(g, members=ms))
    return out, reg


def load_groups():
    import yaml
    return groups_from_registry(yaml.safe_load(open(os.path.join(REPO, REGISTRY)).read()) or {})


def _aliases():
    return {rs._alias(p) for p in lsr._symbol_files()} | {"main"}


def src_binaries(path, reg_groups, aliases):
    parts = path.split("/")
    if parts[0] != "src":
        return set()
    if len(parts) == 2:
        return {"main"}
    if parts[1] == "shared":
        return {m["binary"] for g in reg_groups if g.get("source") == path for m in g.get("members", [])}
    return {parts[1]} if parts[1] in aliases else set()


def asm_binaries(old, aliases):
    if not os.path.isdir(os.path.join(REPO, "asm")):
        return set()
    p = subprocess.run(["grep", "-rlwF", old, "asm"], cwd=REPO, capture_output=True, text=True)
    out = set()
    for f in p.stdout.split():
        top = f.split("/")[1] if f.count("/") >= 2 else ""
        out.add(top if top in aliases else "main")
    return out


LEDGER_NAME_KEYS = ("fn", "unit", "callee", "real")   # name fields of a restruct ledger row; `unit` is ledger_latest's key
LEDGER_SITE_LISTS = ("sites", "bases")               # entries keyed `<bclass>:<base>` (restruct.residue_match)


def ledger_row_rename(r, rx, olds):
    """Pure. A restruct ledger row with every old name token in its name fields and its sites[]/bases[] `base` rewritten
    (T7.c3, C0572: `fn` alone left `unit` and the residue keys on the old name). -> (row, changed)."""
    sub = lambda v: rx.sub(lambda m: olds[m.group(0)], v) if isinstance(v, str) else v
    out, changed = dict(r), False
    for k in LEDGER_NAME_KEYS:
        if k in out and sub(out[k]) != out[k]:
            out[k], changed = sub(out[k]), True
    for k in LEDGER_SITE_LISTS:
        if isinstance(out.get(k), list):
            es = [dict(e, base=sub(e["base"])) if isinstance(e, dict) and sub(e.get("base")) != e.get("base") else e
                  for e in out[k]]
            if es != out[k]:
                out[k], changed = es, True
    return out, changed


def restruct_ledger(olds, dry):
    p = os.path.join(REPO, RESTRUCT_LEDGER)
    if not os.path.exists(p):
        return "absent"
    if not olds:
        return "0"
    rx = re.compile(r"\b(?:%s)\b" % "|".join(sorted(map(re.escape, olds), key=lambda o: (-len(o), o))))
    n, tmp = 0, p + ".rename_sym.tmp"
    with open(p) as f, (open(os.devnull, "w") if dry else open(tmp, "w")) as g:
        for ln in f:
            if rx.search(ln):
                r, changed = ledger_row_rename(json.loads(ln), rx, olds)
                if changed:
                    ln = json.dumps(r) + "\n"
                    n += 1
            g.write(ln)
    if not dry:
        os.replace(tmp, p) if n else os.remove(tmp)
    return str(n)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--spec", required=True, metavar="TSV")
    ap.add_argument("--task", required=True, metavar="T<n>", help="the task id stamped into names.tsv history")
    ap.add_argument("--dry-run", action="store_true", help="plan and report; write nothing")
    a = ap.parse_args()
    if not re.match(r"^T\d+$", a.task):
        raise ValueError("--task must be T<n>, got %r" % a.task)
    stamp = "%s %s" % (phase_of(open(os.path.join(REPO, PHASE_PLAN)).readline()), a.task)
    groups, reg = load_groups()
    rows = parse_spec(open(a.spec).read())
    need = {symbol_file(r["binary"]) for r in expand(rows, groups)}
    symtexts = {p: open(os.path.join(REPO, p)).read() for p in need if os.path.exists(os.path.join(REPO, p))}
    aliases = _aliases()
    names_path = os.path.join(REPO, rs.NAMES_TSV)
    planned, newtexts, ntext, nrows = prepare(rows, groups, symtexts, open(names_path).read(), aliases, stamp)
    touched = {r["binary"] for r in planned}
    spec_rel = os.path.relpath(os.path.abspath(a.spec), REPO)
    # one pattern per distinct (old, new), first-seen order: a class row repeats its pair once per member
    # (141 for an overlay-base class); a repeat finds nothing once the first has replaced old, so output is unchanged
    pats = [(o, n, rewrite_re(o)) for o, n in dict.fromkeys((r["old"], r["new"]) for r in planned)]
    for r in planned:
        print("[rename_sym] %s -> %s (%s, %s) in %s" % (r["old"], r["new"], r["addr"], r["binary"], r["symfile"]))
        touched |= asm_binaries(r["old"], aliases)
    if not a.dry_run:
        for p, t in newtexts.items():
            open(os.path.join(REPO, p), "w").write(t)
    regen, rewritten = {}, []
    skip = set(rs.HISTORY)
    for path in _git("ls-files", "-z").split("\0"):
        if not path or path.startswith(tuple(skip)) or path in (spec_rel, rs.NAMES_TSV):
            continue
        fp = os.path.join(REPO, path)
        if not os.path.isfile(fp) or os.path.islink(fp):
            continue
        raw = open(fp, "rb").read()
        if b"\0" in raw or not any(o.encode() in raw for o, _, _ in pats):
            continue
        text = raw.decode("utf-8", "surrogateescape")
        if not any(rx.search(text) for _, _, rx in pats):
            continue
        cmd = regen_cmd(path, "\n".join(text.split("\n", 3)[:3]))
        if cmd:
            regen.setdefault(cmd, []).append(path)
            continue
        n = 0
        for _, new, rx in pats:
            text, k = rx.subn(new, text)
            n += k
        rewritten.append((path, n))
        if path.startswith("config/symbols"):
            touched.add(rs._alias(path) if path != "config/symbols.us.txt" else "main")
        touched |= src_binaries(path, reg, aliases)
        if not a.dry_run:
            open(fp, "wb").write(text.encode("utf-8", "surrogateescape"))
    if not a.dry_run:
        open(names_path, "w").write(ntext)
    led = restruct_ledger({r["old"]: r["new"] for r in planned}, a.dry_run)
    verb = "would rewrite" if a.dry_run else "rewrote"
    print("[rename_sym] symbol files: %s" % ", ".join(sorted(newtexts)))
    print("[rename_sym] %s %d token(s) in %d file(s):" % (verb, sum(n for _, n in rewritten), len(rewritten)))
    for p, n in rewritten:
        print("  %s  %d" % (p, n))
    print("[rename_sym] names.tsv: %s %d row(s): %s" % ("would write" if a.dry_run else "wrote", len(nrows),
                                                         ", ".join("%s (%s)" % (v["name"], v["scope"]) for v in nrows)))
    print("[rename_sym] restruct ledger fn keys %s: %s" % (verb, led))
    print("[rename_sym] binaries: %s" % " ".join(sorted(touched)))
    for b in sorted(touched):
        print("  ghidra %s: %s" % (b, GHIDRA.get(b, "none tracked")))
    for b in sorted(touched):
        print("  regenerate: make extract BINARY=%s" % b)
    for cmd, ps in sorted(regen.items()):
        print("  regenerate: %s   (%s)" % (cmd, ", ".join(ps)))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except ValueError as e:
        sys.exit("[rename_sym] %s" % e)
