#!/usr/bin/env python3
"""rename_sym.py — apply symbol renames: symbol files, token rewrite, names ledger row (P3.42 T3).

  rename_sym.py --spec TSV [--dry-run]

Spec TSV (tab, header line): old new addr binary kind basis confidence evidence conflict citation.
  binary  an alias (main, resident, ov_SC01_077, ...) or `class:<config/dedup.us.yaml id>`: one row per
          member (old = member name, addr = member vram); members in one binary get distinct names
          new, new_2, new_3 in vram order.
Per planned row:
  1. its symbol file (main -> config/symbols.us.txt, else config/symbols.<alias>.txt): the line naming old
     is renamed; a placeholder old (func_/D_<ADDR>) with no line gets one, in address order, and the
     `// count=N` header is updated.
  2. `\\bold\\b` is rewritten in every tracked text file except rename_scan.HISTORY paths, generated files
     (first 3 lines say `generated by tools/<x>`, or a path under GENERATED), config/names.tsv, the spec
     itself, and header-file tokens `func_<ADDR>(__\\w+)?.h` (share headers are named by vram, never renamed).
     A generated file that mentions old prints `regenerate: <cmd>` instead.
  3. config/names.tsv gets a row: name=new, scope=the symbol file's alias (`us` for main: what
     rename_scan --ledger accepts), tier guess iff new starts guess_, history=old.
  4. restruct's name-keyed ledger (tools/restruct.py:107, .run/P37/restruct/ledger.jsonl): rows whose
     `fn` is old get new; the count is printed.
Then prints the touched binaries (symbol-file owners, binaries of rewritten src/ files, binaries whose asm/
mentions old), their tracked Ghidra programs (config/ghidra/ROSTER.md) and the regenerate commands.
Verify with tools/rename_scan.py --spec TSV after `make extract` + gates. --dry-run writes nothing.
The planner (parse_spec, expand, edit_symbols, plan) is pure; rename_scan --selftest covers it.
"""
import argparse, json, os, re, subprocess, sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import lint_symbol_refs as lsr      # the ONE symbol-file parser
import rename_scan as rs            # HISTORY, COLUMNS, PLACEHOLDER, NAMES_TSV

REPO = lsr.REPO
SPEC_COLS = ("old", "new", "addr", "binary", "kind", "basis", "confidence", "evidence", "conflict", "citation")
REGISTRY = "config/dedup.us.yaml"
# the card's generated list (HOW_WE_WORK.md "Generated"): path prefix -> regenerate command
GENERATED = {"asm/": "make extract BINARY=<alias>", "extracted/": "make extract BINARY=<alias>",
             "assets/": "make extract BINARY=<alias>", "build/": "make check BINARY=<alias>",
             "docs/tool-index.md": "make kit-corpus",
             "config/ghidra/types/": "/usr/bin/python3 tools/ghidra_types.py --write"}
REPORT_GENERATORS = ("tools/progress.py", "tools/dup_report.py", "tools/difficulty.py")   # Makefile `report`
GHIDRA = {"main": "SLUS_007.26", "resident": "resident", "ov_SC01_077": "ov_SC01_077",
          "ov_SC06_018": "ov_SC06_018"}    # config/ghidra/ROSTER.md:10-17 (the proto programs hold no game names)
RESTRUCT_LEDGER = ".run/P37/restruct/ledger.jsonl"    # tools/restruct.py:107 LEDGER
GEN_RE = re.compile(r"generated by (tools/[\w./-]+)([^)\n]*)")


# ---------------------------------------------------------------- planner (pure)
def parse_spec(text):
    """-> [dict per SPEC_COLS]. Header line required; # comments and blank lines skipped."""
    rows, header = [], None
    for ln in text.splitlines():
        if not ln.strip() or ln.startswith("#"):
            continue
        f = ln.split("\t")
        if header is None:
            if tuple(f) != SPEC_COLS:
                raise ValueError("spec header must be: " + "\\t".join(SPEC_COLS))
            header = f
            continue
        if len(f) != len(SPEC_COLS):
            raise ValueError("spec row has %d fields, needs %d: %r" % (len(f), len(SPEC_COLS), ln))
        rows.append(dict(zip(SPEC_COLS, f)))
    return rows


def symbol_file(alias):
    return "config/symbols.us.txt" if alias == "main" else "config/symbols.%s.txt" % alias


def file_alias(alias):
    return "us" if alias == "main" else alias


def _addr(a):
    return "0x%08X" % int(a, 16)


def expand(rows, groups):
    """groups = {id: [{binary, vram, name}]}. -> one row per (row, member); class members in one binary get
    new, new_2, ... in vram order. Plain rows pass through with a normalized addr."""
    out = []
    for r in rows:
        b = r["binary"]
        if not b.startswith("class:"):
            out.append(dict(r, addr=_addr(r["addr"])))
            continue
        gid = b[len("class:"):]
        if gid not in groups:
            raise ValueError("no registry group %r" % gid)
        n = {}
        for m in sorted(groups[gid], key=lambda m: (m["binary"], int(str(m["vram"]), 16))):
            k = n[m["binary"]] = n.get(m["binary"], 0) + 1
            out.append(dict(r, old=m["name"], addr=_addr(str(m["vram"])), binary=m["binary"],
                            new=r["new"] if k == 1 else "%s_%d" % (r["new"], k)))
    return out


def edit_symbols(text, old, new, addr, kind):
    """-> text with old renamed to new on its line, or (placeholder old, no line) a new line in address
    order plus the `// count=N` header bumped. Raises on a conflict."""
    lines = text.split("\n")
    want = int(addr, 16)
    at, insert = None, None
    for i, ln in enumerate(lines):
        for nm, ad in lsr.iter_symbol_defs(ln):
            if nm == new:
                raise ValueError("%s already defined" % new)
            if nm == old:
                at = i
            elif int(ad, 16) == want and re.search(r"//\s*%s\b" % kind, ln):
                raise ValueError("0x%08X already named %s" % (want, nm))
            if insert is None and int(ad, 16) > want:
                insert = i
    if at is not None:
        lines[at] = re.sub(r"^%s\s*=" % re.escape(old), "%-32s =" % new, lines[at])
        return "\n".join(lines)
    if not rs.PLACEHOLDER.match(old):
        raise ValueError("%s has no symbol line and is not a placeholder" % old)
    new_ln = "%-32s = %s; // %s" % (new, addr, kind)
    if insert is None:                                 # after the last definition
        insert = max((i for i, ln in enumerate(lines) if list(lsr.iter_symbol_defs(ln))), default=len(lines) - 1) + 1
    lines.insert(insert, new_ln)
    for i, ln in enumerate(lines):
        m = re.match(r"^(//\s*count=)(\d+)\s*$", ln)
        if m:
            lines[i] = m.group(1) + str(int(m.group(2)) + 1)
            break
    return "\n".join(lines)


def plan(rows, groups, symtexts):
    """symtexts = {symbol-file path: text}. -> (planned rows with `symfile`, {path: new text}). Pure."""
    planned, texts = [], dict(symtexts)
    names = set()
    for r in expand(rows, groups):
        if (r["new"], r["binary"]) in names:
            raise ValueError("duplicate new name %s in %s" % (r["new"], r["binary"]))
        names.add((r["new"], r["binary"]))
        p = symbol_file(r["binary"])
        if p not in texts:
            raise ValueError("no symbol file %s for binary %s" % (p, r["binary"]))
        texts[p] = edit_symbols(texts[p], r["old"], r["new"], r["addr"], r["kind"])
        planned.append(dict(r, symfile=p))
    return planned, {p: t for p, t in texts.items() if t != symtexts.get(p)}


def rewrite_re(old):
    return re.compile(r"\b%s\b(?!(?:__\w+)?\.h\b)" % re.escape(old))


def names_row(r):
    tier = "guess" if r["new"].startswith("guess_") else "cited"
    v = dict(name=r["new"], kind=r["kind"], scope=file_alias(r["binary"]), addr=r["addr"], tier=tier,
             basis=r["basis"], confidence=r["confidence"], evidence=r["evidence"], conflict=r["conflict"],
             history=r["old"], citation=r["citation"])
    return "\t".join(v[c] for c in rs.COLUMNS)


def regen_cmd(path, head):
    """-> the regenerate command when path is generated, else None."""
    for pre, cmd in GENERATED.items():
        if path.startswith(pre):
            parts = path.split("/")
            return cmd.replace("<alias>", parts[1] if pre == "asm/" and len(parts) > 2 else "main")
    m = GEN_RE.search(head)
    if not m:
        return None
    if m.group(1) in REPORT_GENERATORS:
        b = re.search(r"\.((?:ov|md)_\w+|resident)\.md$", path)
        return "make report BINARY=%s" % (b.group(1) if b else "main")
    return ("/usr/bin/python3 %s%s" % (m.group(1), m.group(2).split(" —")[0])).rstrip()


# ---------------------------------------------------------------- apply
def _git(*args):
    return subprocess.run(("git",) + args, cwd=REPO, capture_output=True, text=True, check=True).stdout


def load_groups():
    import yaml
    d = yaml.safe_load(open(os.path.join(REPO, REGISTRY)).read()) or {}
    return {g["id"]: g.get("members", []) for g in d.get("groups", [])}, d.get("groups", [])


def _aliases():
    return {rs._alias(p) for p in lsr._symbol_files()} | {"main"}


def src_binaries(path, reg_groups, aliases):
    parts = path.split("/")
    if parts[0] != "src":
        return set()
    if len(parts) == 2:
        return {"main"}
    if parts[1] == "shared":
        return {m["binary"] for g in reg_groups if g.get("source") == path for m in g.get("members", [])}
    return {parts[1]} if parts[1] in aliases else set()


def asm_binaries(old, aliases):
    if not os.path.isdir(os.path.join(REPO, "asm")):
        return set()
    p = subprocess.run(["grep", "-rlwF", old, "asm"], cwd=REPO, capture_output=True, text=True)
    out = set()
    for f in p.stdout.split():
        top = f.split("/")[1] if f.count("/") >= 2 else ""
        out.add(top if top in aliases else "main")
    return out


def restruct_ledger(olds, dry):
    p = os.path.join(REPO, RESTRUCT_LEDGER)
    if not os.path.exists(p):
        return "absent"
    n, tmp = 0, p + ".rename_sym.tmp"
    with open(p) as f, (open(os.devnull, "w") if dry else open(tmp, "w")) as g:
        for ln in f:
            if any(o in ln for o in olds):
                r = json.loads(ln)
                if r.get("fn") in olds:
                    r["fn"] = olds[r["fn"]]
                    ln = json.dumps(r) + "\n"
                    n += 1
            g.write(ln)
    if not dry:
        os.replace(tmp, p) if n else os.remove(tmp)
    return str(n)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--spec", required=True, metavar="TSV")
    ap.add_argument("--dry-run", action="store_true", help="plan and report; write nothing")
    a = ap.parse_args()
    groups, reg = load_groups()
    rows = parse_spec(open(a.spec).read())
    need = {symbol_file(r["binary"]) for r in expand(rows, groups)}
    symtexts = {p: open(os.path.join(REPO, p)).read() for p in need if os.path.exists(os.path.join(REPO, p))}
    planned, newtexts = plan(rows, groups, symtexts)
    aliases = _aliases()
    touched = {r["binary"] for r in planned}
    spec_rel = os.path.relpath(os.path.abspath(a.spec), REPO)
    pats = [(r["old"], r["new"], rewrite_re(r["old"])) for r in planned]
    for r in planned:
        print("[rename_sym] %s -> %s (%s, %s) in %s" % (r["old"], r["new"], r["addr"], r["binary"], r["symfile"]))
        touched |= asm_binaries(r["old"], aliases)
    if not a.dry_run:
        for p, t in newtexts.items():
            open(os.path.join(REPO, p), "w").write(t)
    regen, rewritten = {}, []
    skip = set(rs.HISTORY)
    for path in _git("ls-files", "-z").split("\0"):
        if not path or path.startswith(tuple(skip)) or path in (spec_rel, rs.NAMES_TSV):
            continue
        fp = os.path.join(REPO, path)
        if not os.path.isfile(fp) or os.path.islink(fp):
            continue
        raw = open(fp, "rb").read()
        if b"\0" in raw or not any(o.encode() in raw for o, _, _ in pats):
            continue
        text = raw.decode("utf-8", "surrogateescape")
        if not any(rx.search(text) for _, _, rx in pats):
            continue
        cmd = regen_cmd(path, "\n".join(text.split("\n", 3)[:3]))
        if cmd:
            regen.setdefault(cmd, []).append(path)
            continue
        n = 0
        for _, new, rx in pats:
            text, k = rx.subn(new, text)
            n += k
        rewritten.append((path, n))
        if path.startswith("config/symbols"):
            touched.add(rs._alias(path) if path != "config/symbols.us.txt" else "main")
        touched |= src_binaries(path, reg, aliases)
        if not a.dry_run:
            open(fp, "wb").write(text.encode("utf-8", "surrogateescape"))
    if not a.dry_run:
        with open(os.path.join(REPO, rs.NAMES_TSV), "a") as f:
            for r in planned:
                f.write(names_row(r) + "\n")
    led = restruct_ledger({r["old"]: r["new"] for r in planned}, a.dry_run)
    verb = "would rewrite" if a.dry_run else "rewrote"
    print("[rename_sym] symbol files: %s" % ", ".join(sorted(newtexts)))
    print("[rename_sym] %s %d token(s) in %d file(s):" % (verb, sum(n for _, n in rewritten), len(rewritten)))
    for p, n in rewritten:
        print("  %s  %d" % (p, n))
    print("[rename_sym] names.tsv: %s %d row(s)" % ("would add" if a.dry_run else "added", len(planned)))
    print("[rename_sym] restruct ledger fn keys %s: %s" % (verb, led))
    print("[rename_sym] binaries: %s" % " ".join(sorted(touched)))
    for b in sorted(touched):
        print("  ghidra %s: %s" % (b, GHIDRA.get(b, "none tracked")))
    for b in sorted(touched):
        print("  regenerate: make extract BINARY=%s" % b)
    for cmd, ps in sorted(regen.items()):
        print("  regenerate: %s   (%s)" % (cmd, ", ".join(ps)))
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except ValueError as e:
        sys.exit("[rename_sym] %s" % e)
